#!/usr/bin/env node
/**
 * build-sitemap.js — sitemap architecture generator (batch
 * batch-sitemap-architecture-2026-11-02). Supersedes the Phase-1 differ,
 * which generated a single urlset from data/pages.json and byte-diffed it
 * against the live sitemap: the live sitemap is now an index of sections,
 * so this generator WRITES the architecture into the Pages tree and proves
 * set equality before writing (it fails the seal otherwise).
 *
 * https://theflatratemovers.com/sitemap.xml is a sitemap INDEX referencing
 * three section sitemaps plus the Google News sitemap:
 *   /sitemaps/pages.xml     — content pages
 *   /sitemaps/datasets.xml  — the /datasets/ landings + the dataset JSON files
 *   /sitemaps/blog.xml      — the blog hub + every published ledger post
 *   /news-sitemap.xml       — generated by build-news-sitemap.js (Spec A);
 *                             referenced by the index, never written here.
 *
 * SECTION ASSIGNMENT RULE (declared, applied in this order):
 *   1. datasets — every registry page whose URL path starts with /datasets/,
 *      plus every published dataset file (public/datasets-*.json) at its
 *      root URL.
 *   2. blog — the blog hub (/blog/) plus every registry page whose slug is a
 *      published post in the blog ledger.
 *   3. pages — every remaining registry page.
 * The union of the three sections equals the registry pages + the dataset
 * files exactly; the classes are disjoint by construction and the generator
 * proves both properties on every run.
 *
 * lastmod: registry pages carry their own lastmod in data/pages.json.
 * Dataset files keep the lastmod the pre-architecture sitemap (or the
 * existing datasets section) already published for them — continuity, never
 * invented; a brand-new dataset file falls back to its file mtime (UTC date).
 *
 * Runs inside every seal (seal.py phase 2b), before routes/middleware and
 * before the digest phase, so the sealed estate always carries the current
 * architecture.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const os = require('os');

const MACHINE = path.resolve(__dirname, '..');
const PATHS = JSON.parse(fs.readFileSync(path.join(MACHINE, 'paths.json'), 'utf8'));
const PUBLIC = PATHS.public_dir;
const LEDGER = path.join(os.homedir(), 'workspace/theflatratemovers/blog-project/ledger.csv');
const SITE = 'https://theflatratemovers.com';
const SECTIONS_DIR = path.join(PUBLIC, 'sitemaps');

function fail(msg) { console.error('build-sitemap: FAIL — ' + msg); process.exit(1); }

function parseCsv(text) {
  const rows = []; let row = [], field = '', inQ = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQ) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else inQ = false; }
      else field += c;
    } else if (c === '"') inQ = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); field = ''; rows.push(row); row = []; }
    else if (c !== '\r') field += c;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows;
}

function locLastmodMap(file) {
  const map = new Map();
  if (!fs.existsSync(file)) return map;
  const xml = fs.readFileSync(file, 'utf8');
  for (const m of xml.matchAll(/<url><loc>(.*?)<\/loc><lastmod>(.*?)<\/lastmod><\/url>/g)) {
    map.set(m[1], m[2]);
  }
  return map;
}

function urlsetXml(entries) {
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ];
  for (const e of entries) lines.push(`  <url><loc>${e.url}</loc><lastmod>${e.lastmod}</lastmod></url>`);
  lines.push('</urlset>');
  return lines.join('\n') + '\n';
}

function main() {
  const registry = JSON.parse(fs.readFileSync(path.join(MACHINE, 'data/pages.json'), 'utf8'));
  const pages = registry.pages;
  if (!pages.length) fail('page registry is empty');
  for (const p of pages) {
    if (!p.url || !p.lastmod) fail('page missing url or lastmod: ' + JSON.stringify(p.slug));
    if (p.url.includes('#')) fail('hash URL in registry (must never happen): ' + p.url);
    if (!p.url.startsWith(SITE + '/')) fail('non-canonical URL in registry: ' + p.url);
  }

  // Published blog slugs from the ledger (the blog classifier of record).
  const rows = parseCsv(fs.readFileSync(LEDGER, 'utf8'));
  const header = rows[0];
  const slugIx = header.indexOf('slug');
  const statusIx = header.indexOf('status');
  if (slugIx < 0 || statusIx < 0) fail('ledger header lacks slug/status columns');
  const blogSlugs = new Set();
  for (const row of rows.slice(1)) {
    if (row[slugIx] && /published/i.test(row[statusIx] || '')) blogSlugs.add(row[slugIx].trim());
  }

  // Dataset-file lastmod continuity: pre-architecture sitemap or the
  // existing datasets section, whichever is present.
  const prior = locLastmodMap(path.join(PUBLIC, 'sitemap.xml'));
  const priorSection = locLastmodMap(path.join(SECTIONS_DIR, 'datasets.xml'));
  for (const [k, v] of priorSection) if (!prior.has(k)) prior.set(k, v);

  const datasetFiles = fs.readdirSync(PUBLIC)
    .filter((f) => /^datasets-.*\.json$/.test(f)).sort();

  const sections = { pages: [], datasets: [], blog: [] };
  for (const p of pages) {
    const entry = { url: p.url, lastmod: p.lastmod };
    const urlPath = new URL(p.url).pathname;
    if (urlPath.startsWith('/datasets/')) sections.datasets.push(entry);
    else if (p.slug === 'blog' || blogSlugs.has(p.slug)) sections.blog.push(entry);
    else sections.pages.push(entry);
  }
  for (const f of datasetFiles) {
    const url = SITE + '/' + f;
    let lastmod = prior.get(url);
    if (!lastmod) {
      lastmod = fs.statSync(path.join(PUBLIC, f)).mtime.toISOString().slice(0, 10);
    }
    sections.datasets.push({ url, lastmod });
  }
  for (const key of Object.keys(sections)) sections[key].sort((a, b) => a.url.localeCompare(b.url));

  // Set-equality proof: disjoint sections whose union is exactly the
  // registry pages plus the dataset files.
  const expected = new Set([
    ...pages.map((p) => p.url),
    ...datasetFiles.map((f) => SITE + '/' + f),
  ]);
  const seen = new Set();
  for (const key of Object.keys(sections)) {
    for (const e of sections[key]) {
      if (seen.has(e.url)) fail('URL appears in two sections: ' + e.url);
      seen.add(e.url);
    }
  }
  if (seen.size !== expected.size || [...expected].some((u) => !seen.has(u))) {
    fail(`section union (${seen.size}) != expected set (${expected.size})`);
  }
  const blogMissing = [...blogSlugs].filter((s) => !pages.some((p) => p.slug === s));
  if (blogMissing.length) fail('ledger posts missing from the registry: ' + blogMissing.join(', '));

  fs.mkdirSync(SECTIONS_DIR, { recursive: true });
  for (const key of Object.keys(sections)) {
    fs.writeFileSync(path.join(SECTIONS_DIR, key + '.xml'), urlsetXml(sections[key]));
  }
  const indexXml = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    `  <sitemap><loc>${SITE}/sitemaps/pages.xml</loc></sitemap>`,
    `  <sitemap><loc>${SITE}/sitemaps/datasets.xml</loc></sitemap>`,
    `  <sitemap><loc>${SITE}/sitemaps/blog.xml</loc></sitemap>`,
    `  <sitemap><loc>${SITE}/news-sitemap.xml</loc></sitemap>`,
    '</sitemapindex>',
  ].join('\n') + '\n';
  fs.writeFileSync(path.join(PUBLIC, 'sitemap.xml'), indexXml);

  console.log(JSON.stringify({
    sections: { pages: sections.pages.length, datasets: sections.datasets.length, blog: sections.blog.length },
    union: seen.size, expected: expected.size,
    index: ['sitemaps/pages.xml', 'sitemaps/datasets.xml', 'sitemaps/blog.xml', 'news-sitemap.xml'],
  }, null, 1));
}

main();
