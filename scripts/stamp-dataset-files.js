#!/usr/bin/env node
/* stamp-dataset-files.js — Q124 textual dateModified stamper.
 *
 * Batch Q124 (2026-11-03), Henry's Q2=A ruling: EVERY dataset
 * file's internal date stamps equal its lastmod-ledger date.
 * Generator-owned dataset files consume the seal's FB3_STAMPS map
 * themselves (ports at seal phase 0.5, intent-coverage at phase 1,
 * search-index / answer-evidence / local-graph-registry /
 * archive-registry at phase 2). Every OTHER datasets-*.json is an
 * authored static file; this tool stamps it TEXTUALLY — only the
 * `"dateModified": "YYYY-MM-DD"` value tokens are rewritten, so
 * the file's formatting and every other byte survive untouched.
 *
 * Runs inside the seal at phase 0.5 (after build-ports, before
 * the phase-1 rubric, which digests the dataset files), with
 * FB3_STAMPS pointing at the phase-0 stamps map. Fail-loud:
 * missing stamps entry, or a token/field count mismatch (a
 * dateModified value that is not a plain date string, or prose
 * carrying the token shape), aborts the seal.
 *
 * verify.js S-7f asserts the outcome estate-wide.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = process.env.FRM_ROOT || path.resolve(__dirname, '..');
let REG = {};
try { REG = JSON.parse(fs.readFileSync(path.join(ROOT, 'paths.json'), 'utf8')); } catch (_) { /* env override or defaults below */ }
const PUB = process.env.FRM_PUB || REG.public_dir;
const SITE = 'https://theflatratemovers.com';

// Regenerated by seal-phase generators that consume FB3_STAMPS
// themselves; excluded here so the two mechanisms never fight.
const GENERATOR_OWNED = new Set([
  'datasets-ports.json',
  'datasets-intent-coverage.json',
  'datasets-search-index.json',
  'datasets-answer-evidence.json',
  'datasets-answer-evidence-questions.json',
  'datasets-local-graph-registry.json',
  'datasets-archive-registry.json',
]);

function main() {
  const stampsPath = process.env.FB3_STAMPS;
  if (!stampsPath) throw new Error('FB3_STAMPS is required (the seal phase-0 stamps map)');
  const stamps = JSON.parse(fs.readFileSync(stampsPath, 'utf8'));
  const files = (stamps && stamps.files) || {};
  const names = fs.readdirSync(PUB).filter((f) => /^datasets-.+\.json$/.test(f)).sort();
  let changed = 0, fields = 0;
  const notes = [];
  for (const name of names) {
    if (GENERATOR_OWNED.has(name)) continue;
    const url = SITE + '/' + name;
    const want = files[url];
    if (!want) throw new Error('stamps.files lacks ' + url + ' — phase 0 must cover every dataset file (Q124)');
    const p = path.join(PUB, name);
    const raw = fs.readFileSync(p, 'utf8');
    // Self-check: textual token count must equal the recursive
    // dateModified field count of the parsed document, so the
    // textual rewrite provably touches exactly the stamp fields.
    const doc = JSON.parse(raw);
    let walkCount = 0;
    const walk = (o) => {
      if (Array.isArray(o)) { o.forEach(walk); return; }
      if (o && typeof o === 'object') {
        if ('dateModified' in o) walkCount++;
        Object.values(o).forEach(walk);
      }
    };
    walk(doc);
    const tokenRe = /"dateModified":\s*"\d{4}-\d{2}-\d{2}"/g;
    const tokenCount = (raw.match(tokenRe) || []).length;
    if (tokenCount !== walkCount) {
      throw new Error(name + ': dateModified token count ' + tokenCount + ' != parsed field count ' + walkCount +
        ' — refusing textual stamping (a value is not a plain date string, or prose carries the token shape)');
    }
    if (!tokenCount) { notes.push(name + ': 0 dateModified fields (nothing to stamp)'); continue; }
    fields += tokenCount;
    const out = raw.replace(/("dateModified":\s*")\d{4}-\d{2}-\d{2}(")/g, '$1' + want + '$2');
    if (out !== raw) { fs.writeFileSync(p, out); changed++; notes.push(name + ': ' + tokenCount + ' field(s) -> ' + want); }
  }
  console.log('stamp-dataset-files: ' + changed + ' file(s) restamped, ' + fields +
    ' dateModified field(s) at ledger values across ' + names.length + ' dataset files (' +
    GENERATOR_OWNED.size + ' generator-owned skipped)');
  for (const n of notes) console.log('  ' + n);
}

main();
